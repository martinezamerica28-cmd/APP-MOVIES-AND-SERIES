const { chromium } = require('playwright');
(async () => {
 const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
 const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
 page.setDefaultTimeout(10000);
 const failures = []; page.on('pageerror', e => failures.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByText('Películas en estreno', { exact: true }).waitFor();
 await page.getByRole('button', { name: 'Ver Más allá de Orión', exact: true }).first().click();
 await page.getByRole('button', { name: 'Calificar con 4 estrellas' }).click();
 await page.getByText('Por ver', { exact: true }).click();
 await page.getByText('♡ Agregar a favoritos', { exact: true }).click();
 await page.getByRole('textbox', { name: 'Tu reseña' }).fill('Una gran aventura.');
 await page.getByText('‹ Volver', { exact: true }).click();
 await page.getByRole('button', { name: 'Abrir menú' }).click();
 await page.getByText('◯ Yo', { exact: true }).click();
 await page.getByPlaceholder('Nombre de la nueva lista').fill('Fin de semana');
 await page.getByText('Crear', { exact: true }).click();
 await page.getByText('Mis favoritos', { exact: true }).waitFor();
 await page.reload();
 await page.getByRole('button', { name: 'Abrir menú' }).click();
 await page.getByText('◯ Yo', { exact: true }).click();
 await page.getByText('Fin de semana', { exact: true }).waitFor();
 await page.getByText('Una gran aventura.', { exact: true }).waitFor();
 await page.getByRole('button', { name: 'Ver Más allá de Orión', exact: true }).first().click();
 await page.getByText('+ Fin de semana', { exact: true }).click();
 await page.getByText('✓ Fin de semana', { exact: true }).waitFor();
 await page.getByText('‹ Volver', { exact: true }).click();
 await page.getByRole('button', { name: 'Abrir menú' }).click();
 await page.getByText('Terror', { exact: true }).click();
 await page.getByRole('button', { name: 'Ver La última luz', exact: true }).waitFor();
 await page.getByRole('textbox', { name: 'Buscar películas y series' }).fill('Órbita');
 await page.getByRole('button', { name: 'Buscar', exact: true }).click();
 await page.getByRole('button', { name: 'Ver Órbita', exact: true }).waitFor();
 if (failures.length) throw Error(failures.join('\n'));
 await page.waitForTimeout(800); // Deja terminar las animaciones de cierre de los modales.
 await page.screenshot({ path: '/tmp/cineclub-smoke.png' });
 console.log('PASS: catálogo, detalle, calificación, estado, reseña, favoritos, listas, persistencia, géneros y búsqueda.');
 await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
